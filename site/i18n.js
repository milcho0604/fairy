/*
 * 자리표시 채우기. app.js(브라우저)와 tools/build.mjs(미리 그리기)가 같이 써요.
 * Fills {token} and {token|조사} placeholders. Shared by app.js and tools/build.mjs.
 */
window.I18N_FILL = (function () {
  // 마지막 글자에 받침이 있나. 한글은 글자로, 숫자는 읽는 소리로, 영어는 끝 글자 소리로 어림해요.
  function batchim(word) {
    var w = String(word).trim();
    var last = w.slice(-1);
    var c = last.charCodeAt(0);
    if (c >= 0xac00 && c <= 0xd7a3) {
      var jong = (c - 0xac00) % 28;
      return { has: jong !== 0, rieul: jong === 8 };
    }
    if (/[0-9]/.test(last)) return { has: '013678'.indexOf(last) >= 0, rieul: '178'.indexOf(last) >= 0 };
    var lw = w.toLowerCase();
    return { has: /(?:[lmnbkpt]|ng|ck)$/.test(lw), rieul: /l$/.test(lw) };
  }
  function josa(word, pair) {
    var b = batchim(word);
    if (pair === '으로로') return b.has && !b.rieul ? '으로' : '로';
    if (pair === '이에요예요') return b.has ? '이에요' : '예요';
    return b.has ? pair.charAt(0) : pair.charAt(1);
  }
  return function fill(str, vars) {
    return String(str).replace(/\{(\^?)(\w+)(?:\|([^}]+))?\}/g, function (m, only, k, pair) {
      if (!Object.prototype.hasOwnProperty.call(vars, k)) return m;
      var v = String(vars[k]);
      if (only) return pair ? josa(v, pair) : '';
      return pair ? v + josa(v, pair) : v;
    });
  };
})();
