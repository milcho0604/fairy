test('할 일: 제목 속 낱말은 그대로 (오인 방지)', () => {
  const titles = [
    '주말 여행 계획', // 맨 앞 그냥 "주말"은 제목일 수 있다 (주말에, 이번 주말은 날짜)
    '주말여행 계획',
    '이번 주 보고서', // 그냥 "이번 주", "이번 달"은 언제인지 모호해 읽지 않는다
    '이번 달 목표 정리',
    '0주 뒤 x',
    '월말정산 서류',
    '다음 주제 정하기',
    '2주간 운동',
    '한 달 동안 금주',
  ];
  for (const text of titles) assert.deepEqual(todo(text), [text, null], text);
});

test('요일과 달에 따라: 금요일의 이번 주까지는 오늘, 일요일의 주말은 오늘, 해 넘기기', () => {
  const table: [string, string, string][] = [
    ['x 이번 주까지', '2026-10-09', '2026-10-09'],
    ['x 주말', '2026-10-10', '2026-10-10'],
    ['x 주말', '2026-10-11', '2026-10-11'],
    ['x 다음 주말', '2026-10-11', '2026-10-17'],
    ['x 다음 주', '2026-10-11', '2026-10-12'],
    ['x 다음 주', '2026-10-12', '2026-10-19'],
    ['x 다음 달', '2026-12-15', '2027-01-01'],
    ['x 다음 달 말', '2026-12-15', '2027-01-31'],
    ['x 한 달 뒤', '2026-01-31', '2026-02-28'],
    ['x 월말', '2028-02-03', '2028-02-29'],
  ];
  for (const [text, day, want] of table) assert.equal(parseQuickTodo(text, day).due, want, `${text} @${day}`);
  assert.equal(koRelDay('이번 달', today), null);
  assert.equal(koRelDay('0달 뒤', today), null);
});

test('일정: 시각 일정과 종일 일정도 같은 날', () => {
  const table: [string, unknown][] = [
    ['다음 주 3시 회의', E('회의', '2026-10-12', at(15))],
    ['주말 2시 브런치', E('브런치', '2026-10-10', at(14))],
    ['주말에 2시 브런치', E('브런치', '2026-10-10', at(14))],
    ['2주 뒤 오후 3시 치과', E('치과', '2026-10-20', at(15))],
    ['다다음 주 금요일 3시 발표', E('발표', '2026-10-23', at(15))],
    ['다음 달 3시 회의', E('회의', '2026-11-01', at(15))], // "3시"는 날짜가 아니다
    ['다음 달 5일 3시 결제', E('결제', '2026-11-05', at(15))],
    ['월말 4시 정산', E('정산', '2026-10-31', at(16))],
    ['30분 뒤 빨래', E('빨래', today, at(9, 30))],
    ['3일 뒤 2시 치과', E('치과', '2026-10-09', at(14))],
  ];
  for (const [text, want] of table) assert.deepEqual(parseQuickEvent(text, today, nine), want, text);
  const allDay: [string, string, string | null][] = [
    ['다음 주말 캠핑', '2026-10-17', null],
    ['한 달 뒤 이사', '2026-11-06', null],
    ['다음 주부터 3일 워크숍', '2026-10-12', '2026-10-14'],
    ['2주 뒤부터 2박 3일 여행', '2026-10-20', '2026-10-22'],
    ['다음 주말 2일간 캠핑', '2026-10-17', '2026-10-18'],
    ['10월 10일부터 12일 여행', '2026-10-10', '2026-10-12'], // 예전 그대로
  ];
  for (const [text, day, last] of allDay) {
    const r = parseEventInput(text, today, nine);
    assert.ok(r && 'allDay' in r, text);
    assert.equal(r.day, day, text);
    assert.equal(r.lastDay, last, text);
  }
});

test('할 일과 일정이 같은 날, 영어와 한국어가 같은 날', () => {
  const pairs: [string, string][] = [
    ['다음 주', 'next week'],
    ['이번 주까지', 'end of week'],
    ['다음 주까지', 'end of next week'],
    ['주말에', 'this weekend'],
    ['다음 주말', 'next weekend'],
    ['월말', 'end of month'],
    ['다음 달 말', 'end of next month'],
    ['다음 달', 'next month'],
    ['2주 뒤', 'in 2 weeks'],
    ['한 달 뒤', 'in a month'],
    ['일주일 뒤', 'in a week'],
    ['모레', 'the day after tomorrow'],
  ];
  for (const [ko, en] of pairs) {
    const due = parseQuickTodo(`x ${ko}`, today).due;
    assert.ok(due, ko);
    assert.equal(parseQuickTodo(`x ${en}`, today).due, due, `${ko} = ${en}`);
    assert.equal(parseQuickEvent(`x ${ko} 3시`, today, nine)?.day, due, `일정 ${ko}`);
  }
});
