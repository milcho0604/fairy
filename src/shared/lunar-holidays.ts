// 설날(음력 1월 1일)과 추석(음력 8월 15일)의 양력 날짜, 2025~2100.
// 한국 음력은 한국 표준시(UTC+9) 기준 합삭과 중기로 정한다 (중국 음력과 하루씩 다른 해가 있다, 2027 설날 등).
// 2025~2050 은 한국천문연구원 음양력 자료(korean-lunar-calendar 패키지)와 하나하나 맞춰 봤고,
// 2051~2100 은 같은 규칙을 천문 계산(PyEphem)으로 돌려 얻었다. 만든 법: scripts/dev/lunar-holidays.py
// 2092 설날은 합삭이 자정 2분 뒤라 천문연 발표가 하루 이를 수도 있다.

/** 2025 년부터 해마다 'MMDD(설날)MMDD(추석)', 다섯 해씩 한 줄 */
const TABLE = [
  '01291006 02170925 02070915 01271003 02130922', // 2025
  '02030912 01231001 02110919 01310908 02190927', // 2030
  '02080916 01281004 02150924 02040913 01241002', // 2035
  '02120921 02010910 01220928 02100917 01301005', // 2040
  '02170925 02060915 01261004 02140922 02020911', // 2045
  '01230930 02110919 02010907 02190926 02080916', // 2050
  '01281005 02150924 02040913 01241002 02120921', // 2055
  '02020909 01220928 02090917 01291006 02170925', // 2060
  '02050915 01261003 02140923 02030911 01230929', // 2065
  '02110919 01310908 02190926 02070916 01271005', // 2070
  '02150924 02050912 01241001 02120920 02020910', // 2075
  '01220928 02090917 01291006 02170926 02060914', // 2080
  '01261003 02140922 02030911 01240929 02110919', // 2085
  '01300908 02180927 02080916 01271005 02150924', // 2090
  '02050913 01251001 02120920 02010910 01210929', // 2095
  '02090918', // 2100
]
  .join(' ')
  .split(' ');

export const LUNAR_FIRST_YEAR = 2025;
export const LUNAR_LAST_YEAR = LUNAR_FIRST_YEAR + TABLE.length - 1;

const iso = (year: number, mmdd: string) => `${year}-${mmdd.slice(0, 2)}-${mmdd.slice(2, 4)}`;

/** 그해 설날과 추석 (YYYY-MM-DD). 표 밖의 해는 undefined */
export function lunarHolidays(year: number): { seollal: string; chuseok: string } | undefined {
  const row = TABLE[year - LUNAR_FIRST_YEAR];
  if (!row) return undefined;
  return { seollal: iso(year, row.slice(0, 4)), chuseok: iso(year, row.slice(4, 8)) };
}
